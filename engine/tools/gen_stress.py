#!/usr/bin/env python3
"""Generates the two heavy benchmark maps, engine/maps/corridor.map and hall.map.

corridor: 24 sectors in a row, 6 units long and 4 wide, every shared edge fully open, so
          standing at one end the view runs through all 24 portals. Floors and ceilings step
          up and down so each portal also carries upper and lower wall pieces. Stresses the
          portal traversal and the number of wall commands.
hall:     one 80x80 sector with 220 sprites, seen across its full width. Stresses floor and
          ceiling spans and sprite columns, with almost no traversal.

Deterministic: fixed seed, small LCG, no use of Python's random module.
Usage: python gen_stress.py [maps_dir]
"""
import sys
from pathlib import Path

SEED = 20261025
N = 24            # corridor sectors
LEN = 6           # corridor sector length
WIDTH = 4         # corridor width


class Lcg:
    def __init__(self, seed):
        self.s = seed & 0x7FFFFFFF

    def next(self):
        self.s = (self.s * 1103515245 + 12345) & 0x7FFFFFFF
        return self.s >> 8

    def below(self, n):
        return self.next() % n


def corridor(rng):
    lines = [
        f"# corridor: {N} sectors of {LEN}x{WIDTH} units in a row with every shared edge open",
        "# (generated by tools/gen_stress.py). From the spawn the view runs through all of them.",
        "",
        "player 2 2 0",
        "",
    ]
    tex = [0, 2, 3, 1]
    for i in range(N):
        x0, x1 = i * LEN, (i + 1) * LEN
        floor = 0.2 * (i % 3) if i % 5 else 0.0
        ceil = 3.2 + 0.4 * ((i * 7) % 4) - (0.8 if i % 6 == 5 else 0.0)
        light = 16 + (i * 5) % 14
        wt = tex[i % 4]
        west = f" portal {i - 1} up 2 low 2" if i > 0 else f" mid {wt}"
        east = f" portal {i + 1} up 2 low 2" if i < N - 1 else " mid 8"

        # west edge is last (x0,WIDTH)->(x0,0); east edge is (x1,0)->(x1,WIDTH)
        lines += [
            f"sector {i} floor {floor:.1f} ceil {ceil:.1f} ftex {(4, 6, 7)[i % 3]} ctex 5 light {light}",
            f"  v {x0} 0 mid {wt}",
            f"  v {x1} 0{east}",
            f"  v {x1} {WIDTH} mid {wt}",
            f"  v {x0} {WIDTH}{west}",
            "end",
            "",
        ]

    for i in range(N):
        if i % 2 == 0:
            side = 0.9 if (i // 2) % 2 == 0 else WIDTH - 0.9
            lines.append(f"thing {i * LEN + 3} {side} {rng.below(3)}")
    return lines


def hall(rng):
    size = 80
    lines = [
        "# hall: a single 80x80 sector with 220 sprites (generated by tools/gen_stress.py).",
        "# Almost no traversal: it stresses floor and ceiling spans and sprite columns.",
        "",
        "player 4 40 0",
        "",
        "sector 0 floor 0 ceil 6 ftex 7 ctex 5 light 26",
        "  v 0 0 mid 0",
        f"  v {size} 0 mid 2",
        f"  v {size} {size} mid 3",
        f"  v 0 {size} mid 1",
        "end",
        "",
    ]
    placed = 0
    while placed < 220:
        x = 3 + rng.below(size - 6)
        y = 3 + rng.below(size - 6)
        if abs(x - 4) < 3 and abs(y - 40) < 3:
            continue          # keep the spawn clear
        lines.append(f"thing {x} {y} {rng.below(3)}")
        placed += 1
    return lines


def write(path, lines):
    path.write_bytes(("\n".join(lines) + "\n").encode())
    print(f"wrote {path}")


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).parent.parent / "maps"
    rng = Lcg(SEED)
    write(out / "corridor.map", corridor(rng))
    write(out / "hall.map", hall(rng))


if __name__ == "__main__":
    main()
