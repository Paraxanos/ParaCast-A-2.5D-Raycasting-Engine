#!/usr/bin/env python3
"""Generates engine/maps/maze.map: a grid of 8x8 rooms joined by 2-unit doorways.

Every room edge is split into three segments (solid, doorway, solid), whether or not the
doorway is open, so neighbouring rooms always share the same vertices. Open doorways are
portals; closed ones are solid wall. Rooms differ in floor height (steps of 0.2, so
neighbours are always climbable), ceiling, light and textures.

Deterministic: a fixed seed and a small LCG, no use of Python's random module.
Usage: python gen_maze.py [output_path]
"""
import sys
from pathlib import Path

N = 6          # rooms per side
S = 8          # room size in units
SEED = 20261023


class Lcg:
    def __init__(self, seed):
        self.s = seed & 0x7FFFFFFF

    def next(self):
        self.s = (self.s * 1103515245 + 12345) & 0x7FFFFFFF
        return self.s >> 8

    def below(self, n):
        return self.next() % n


def cell_id(cx, cy):
    return cy * N + cx


def build_doors(rng):
    """Returns a set of ((cx, cy), (nx, ny)) open doorways, both directions included."""
    visited = {(0, 0)}
    stack = [(0, 0)]
    open_doors = set()
    dirs = [(1, 0), (-1, 0), (0, 1), (0, -1)]

    while stack:
        cx, cy = stack[-1]
        options = [(cx + dx, cy + dy) for dx, dy in dirs
                   if 0 <= cx + dx < N and 0 <= cy + dy < N and (cx + dx, cy + dy) not in visited]
        if not options:
            stack.pop()
            continue
        nx, ny = options[rng.below(len(options))]
        open_doors.add(((cx, cy), (nx, ny)))
        open_doors.add(((nx, ny), (cx, cy)))
        visited.add((nx, ny))
        stack.append((nx, ny))

    for cy in range(N):
        for cx in range(N):
            for dx, dy in ((1, 0), (0, 1)):
                nx, ny = cx + dx, cy + dy
                if nx < N and ny < N and ((cx, cy), (nx, ny)) not in open_doors and rng.below(4) == 0:
                    open_doors.add(((cx, cy), (nx, ny)))
                    open_doors.add(((nx, ny), (cx, cy)))
    return open_doors


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).parent.parent / "maps" / "maze.map"
    rng = Lcg(SEED)
    doors = build_doors(rng)

    lines = [
        "# maze: 6x6 rooms of 8x8 units joined by 2-unit doorways (generated by tools/gen_maze.py).",
        "# 36 sectors, every room edge split in three. Stresses long portal chains, many",
        "# visits per frame, step heights between neighbours, and varied lighting.",
        "",
        f"player {S // 2} {S // 2} 0",
        "",
    ]

    wall_tex = [0, 2, 3, 1]
    floor_tex = [4, 6, 7]

    for cy in range(N):
        for cx in range(N):
            h = rng.next()
            level = (cx * 2 + cy * 3 + h) % 3
            floor = 0.2 * level
            ceil = floor + 2.4 + 0.2 * ((cx + cy) % 3)
            light = 14 + h % 17
            wtex = wall_tex[(cx + cy * 2) % 4]
            ox, oy = cx * S, cy * S

            def door(dx, dy):
                n = (cx + dx, cy + dy)
                if ((cx, cy), n) in doors:
                    return f" portal {cell_id(*n)} up 1 low 1"
                return f" mid {wtex}"

            north, east, south, west = door(0, -1), door(1, 0), door(0, 1), door(-1, 0)
            solid = f" mid {wtex}"

            lines += [
                f"sector {cell_id(cx, cy)} floor {floor:.1f} ceil {ceil:.1f} "
                f"ftex {floor_tex[(cx + cy) % 3]} ctex 5 light {light}",
                f"  v {ox} {oy}{solid}",
                f"  v {ox + 3} {oy}{north}",
                f"  v {ox + 5} {oy}{solid}",
                f"  v {ox + S} {oy}{solid}",
                f"  v {ox + S} {oy + 3}{east}",
                f"  v {ox + S} {oy + 5}{solid}",
                f"  v {ox + S} {oy + S}{solid}",
                f"  v {ox + 5} {oy + S}{south}",
                f"  v {ox + 3} {oy + S}{solid}",
                f"  v {ox} {oy + S}{solid}",
                f"  v {ox} {oy + 5}{west}",
                f"  v {ox} {oy + 3}{solid}",
                "end",
                "",
            ]

    for cy in range(N):
        for cx in range(N):
            r = rng.next()
            if r % 3 == 0:
                lines.append(f"thing {cx * S + 3 + r // 3 % 3} {cy * S + 3 + r // 9 % 3} {r // 27 % 3}")

    out.write_text("\n".join(lines) + "\n", newline="\n") if sys.version_info >= (3, 10) else out.write_bytes(
        ("\n".join(lines) + "\n").encode())
    print(f"wrote {out} ({N * N} sectors)")


if __name__ == "__main__":
    main()
